"""提示词：定义 PPT 元素 -> Markdown 的映射规则。"""

from __future__ import annotations

from .serialize import slide_payload
from .ir import Slide

SYSTEM_PROMPT = """你是 PPT 转 Markdown 的格式转换器。输入是一页幻灯片的元素清单（已按阅读顺序排序），
你要输出这一页对应的 Markdown。

## 输出格式
1. 只输出这一页的 Markdown 正文，不要代码围栏（```），不要 `---` 分隔线，不要任何解释或前后缀。
2. 第一行固定为 `## {页码}. {页标题}`。若该页没有标题，写 `## 幻灯片 {页码}`。
3. 载荷中 `页标题(供参考)` 仅用于生成第一行，不要把标题元素再重复输出一次。
4. 文档的一级标题由程序添加，你不要输出 `#`。
5. 页面内小节用 `###`，更细层级用 `####`，最多到 `####`。

## 元素映射
- 文本框/正文/副标题：输出为普通段落（连续文本）。`<p lvl=N>` 表示原文层级，仅供判断结构。
- 列表：载荷中标了 `bullet=char` 或 `bullet=number` 的段落是列表项。
  - `bullet=char` 用 `- `；`bullet=number` 用 `1. `（Markdown 会自动编号）。
  - `lvl=N` 的缩进为每级 2 个空格。同一层级的相邻项合并为一个列表。
  - 未标 bullet 但语义上明显是并列条目（如“输入电压：… / 输出电流：…”成组出现）时可以转为列表；否则保持段落。
- 行内格式：`<b>…</b>` 转 `**…**`，`<i>…</i>` 转 `*…*`，`<code>…</code>` 转反引号行内代码，嵌套时依次套用。
- `<br>` 是原文换行，Markdown 中保留为 `<br>`。
- 表格：输出 GFM 表格，载荷的「行0」作为表头行。单元格内的 `<br>` 保留。载荷给出「合并」时，
  把合并单元格的值写在主单元格，其余被合并位置留空，并在表格下方用一行说明合并关系（例如
  `> 说明：行0列0「xxx」跨2行2列`）。表格前后各留一个空行。
- 图表：先输出 `### 图表：{标题}`（无标题则 `### 图表`），再输出 GFM 表格：第一列表头为分类名
  （无分类时用“项目”），每个系列一列。若载荷标注「(无可用数据)」，只输出 `### 图表：{标题}`。
- 图片：必须原样输出占位符 `{{IMG1}}` 单独成行，不得改写成路径、不得编造文件名、不得遗漏。
- 附件：必须原样输出占位符 `{{FILE1}}` 单独成行。
- 备注：放在该页最后，格式为 `> **备注**：内容`，多行时每行以 `> ` 开头。

## 内容约束
- 严格保真：不得改写、概括、意译、翻译、润色、补全；保留原文用词、数字、单位、标点与中英文混排。
- 不得添加原文没有的内容，不得输出载荷里不存在的图片/附件占位符。
- 元素顺序遵循载荷顺序；同一行并排的短文本（如标签）可合并为一个段落。
- 若整页只有图片，只输出标题行和图片占位符。
- 只允许出现 `<br>` 这一个 HTML 标签。"""


def build_user_message(slide: Slide, total: int, include_notes: bool = True) -> str:
    return slide_payload(slide, total, include_notes=include_notes)


def build_correction_message(page_no: int, problems: list[str]) -> str:
    bullets = "\n".join(f"- {problem}" for problem in problems)
    return (
        f"你上一次的输出不符合约束，请重新输出第 {page_no} 页的 Markdown。\n"
        f"问题：\n{bullets}\n"
        "注意：图片/附件只能写成 {{IMG编号}} / {{FILE编号}} 占位符，不得写真实路径；"
        "不要代码围栏，不要 --- 分隔线，第一行是 `## 页码. 标题`。"
    )
